public void carregarTabela() {

    DefaultTableModel tabela =
            (DefaultTableModel) jTableImpressoes.getModel();

    tabela.setRowCount(0);

    try {

        ImpressaoDAO dao = new ImpressaoDAO();

        List<Impressao> impressoes = dao.listar();

        for (Impressao impressao : impressoes) {

            String tempo = impressao.getHoras() + "h "
                    + impressao.getMinutos() + "min";

            Object[] linha = {
                impressao.getModelo(),
                impressao.getMaterial(),
                impressao.getCor(),
                impressao.getQuantidade(),
                impressao.getFilamento(),
                tempo,
                impressao.getStatus(),
                "Editar | Excluir"
            };

            tabela.addRow(linha);
        }

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar impressões: " + e.getMessage()
        );
    }
}

public void excluirImpressao() {

    int linha = jTableImpressoes.getSelectedRow();

    if (linha == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Selecione uma impressão para excluir.");
        return;
    }

    int confirmacao = javax.swing.JOptionPane.showConfirmDialog(
            this,
            "Deseja realmente excluir essa impressão?",
            "Confirmar exclusão",
            javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (confirmacao == javax.swing.JOptionPane.YES_OPTION) {

        try {
            int indice = jTableImpressoes.convertRowIndexToModel(linha);

            ImpressaoDAO dao = new ImpressaoDAO();

            java.util.List<Impressao> impressoes = dao.listar();

            int id = impressoes.get(indice).getId();

            dao.excluir(id);

            carregarTabela();

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Impressão excluída com sucesso!");

        } catch (java.sql.SQLException e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Erro ao excluir impressão: " + e.getMessage());
        }
    }
}

public void editarImpressao() {

    int linha = jTableImpressoes.getSelectedRow();

    if (linha == -1) {
        javax.swing.JOptionPane.showMessageDialog(this,
                "Selecione uma impressão para editar.");
        return;
    }

    try {

        int indice = jTableImpressoes.convertRowIndexToModel(linha);

        ImpressaoDAO dao = new ImpressaoDAO();

        List<Impressao> impressoes = dao.listar();

        int id = impressoes.get(indice).getId();

        TelaInicial telaInicial = (TelaInicial)
                javax.swing.SwingUtilities.getWindowAncestor(this);

        telaInicial.mostrarTela(new Cadastro(id));

    } catch (SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(this,
                "Erro ao abrir impressão: " + e.getMessage());
    }
}
