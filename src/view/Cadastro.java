public Cadastro(int id) {
    initComponents();

    try {
        ImpressaoDAO dao = new ImpressaoDAO();
        Impressao impressao = dao.buscarPorId(id);

        if (impressao == null) {
            JOptionPane.showMessageDialog(this, "Impressão não encontrada.");
            return;
        }

        this.indiceEdicao = id;

        jTextFieldModelo.setText(impressao.getModelo());
        jComboBoxMaterial.setSelectedItem(impressao.getMaterial());
        jTextFieldCor.setText(impressao.getCor());
        jSpinnerQtdPcs.setValue(impressao.getQuantidade());
        jTextFieldFilamentoUsado.setText(String.valueOf(impressao.getFilamento()));
        jTextFieldHoras.setText(String.valueOf(impressao.getHoras()));
        jTextFieldMinutos.setText(String.valueOf(impressao.getMinutos()));
        jComboBoxStatus.setSelectedItem(impressao.getStatus());

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Erro ao carregar impressão: " + e.getMessage());
    }
}

