    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        // TODO add your handling code here:                                              


        try {
            String modelo = jTextFieldModelo.getText();
            String material = jComboBoxMaterial.getSelectedItem().toString();
            String cor = jTextFieldCor.getText();

            int quantidade = (int) jSpinnerQtdPcs.getValue();

            float filamento = Float.parseFloat(
                jTextFieldFilamentoUsado.getText().replace(",", ".")
            );

            int horas = Integer.parseInt(jTextFieldHoras.getText());
            int minutos = Integer.parseInt(jTextFieldMinutos.getText());

            String status = jComboBoxStatus.getSelectedItem().toString();

            Impressao novaImpressao = new Impressao(
                modelo, material, cor, quantidade,
                filamento, horas, minutos, status
            );

            ImpressaoDAO dao = new ImpressaoDAO();

            if (indiceEdicao == -1) {

                dao.adicionar(novaImpressao);

                JOptionPane.showMessageDialog(
                    this, "Impressão cadastrada com sucesso!"
                );

            } else {

                novaImpressao.setId(indiceEdicao);
                dao.atualizar(novaImpressao);

                JOptionPane.showMessageDialog(
                    this, "Impressão atualizada com sucesso!"
                );
            }

            TelaInicial telaInicial = (TelaInicial)
                javax.swing.SwingUtilities.getWindowAncestor(this);

            telaInicial.mostrarTela(new Impressoes());

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(
                this, "Confira os campos numéricos."
            );

        } catch (SQLException e) {

            JOptionPane.showMessageDialog(
                this, "Erro ao salvar impressão: " + e.getMessage()
            );
        }

    }//GEN-LAST:event_jButtonSalvarActionPerformed

