    private void start(){
        
        setLocationRelativeTo(null); // Para iniciar centralizado
        
        c = new ControladorTela(jDesktopPane1);
        
        // Para inicializar na tela Inicio
        
        destacarBotao(jPanel3); // Já deixa o botão Início destacado na abertura
        
        java.awt.EventQueue.invokeLater(new Runnable() {
            public void run() {
                c.carregarInicio();
    
            }
        });
    }
    
    private void destacarBotao(javax.swing.JPanel botaoAtivo) {
    // 1. Reseta todos os botões para a cor escura do fundo (jPanel1)
    java.awt.Color corPadrao = new java.awt.Color(0, 51, 204);
    jPanel3.setBackground(corPadrao); // Botão Início
    jPanel4.setBackground(corPadrao); // Botão Impressões
    jPanel2.setBackground(corPadrao); // Botão Calculadora

    // 2. Destaca APENAS o botão que foi clicado com a cor clara
    if (botaoAtivo != null) {
        botaoAtivo.setBackground(new java.awt.Color(51, 102, 255));
    }
}

    
    
